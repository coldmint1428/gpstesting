// A uuid v4, for the places where the value has to satisfy a uuid COLUMN.
//
// crypto.randomUUID() is the obvious way to make one, and it is missing wherever the page is not
// in a secure context -- which includes every plain-http origin this app is served from on a phone
// on the same network. Its absence is not the same thing as having no randomness, though:
// crypto.getRandomValues() DOES work over http, so the fallback still draws from the platform's
// generator, and only a browser with no Web Crypto at all drops to Math.random.
//
// Nothing here is ever a secret -- it is a row's name, not its key -- which is why the last
// fallback is acceptable rather than alarming. Anything that IS a secret is generated by the
// database (see gen_random_uuid() in the migrations).
export function uuid4() {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID()
  }

  const bytes = new Uint8Array(16)
  if (typeof crypto !== 'undefined' && typeof crypto.getRandomValues === 'function') {
    crypto.getRandomValues(bytes)
  } else {
    for (let i = 0; i < bytes.length; i++) bytes[i] = Math.floor(Math.random() * 256)
  }

  bytes[6] = (bytes[6] & 0x0f) | 0x40 // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80 // variant 10

  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('')
  return (
    hex.slice(0, 8) +
    '-' +
    hex.slice(8, 12) +
    '-' +
    hex.slice(12, 16) +
    '-' +
    hex.slice(16, 20) +
    '-' +
    hex.slice(20)
  )
}
